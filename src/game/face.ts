export function rewardLine(lang: Lang, earned: number, watts: number, parts: string[], booted: boolean, bests: Record<string, number>): string {
  const s = screen(lang);
  const fill = (t: string, extra: Record<string, string> = {}) =>
    t.replace("{n}", String(earned)).replace("{watts}", String(watts)).replace(/\{(\w+)\}/g, (_, k) => extra[k] ?? "");
  if (booted) return fill(s.alreadyOn);
  const pending = PARTS.find((part) => {
    const board = courseForPart(part.id);
    return !!board && bests[board.id] == null;
  });
  if (pending) return fill(s.nextReward, { part: partLabel(lang, pending.id, pending.name), cost: String(pending.cost) });
  const uninstalled = nextPart(parts);
  if (uninstalled) return fill(s.everyWon, { part: partLabel(lang, uninstalled.id, uninstalled.name) });
  return fill(s.bootPc);
}

export function cheerLine(lang: Lang, place: number, name: string): string {
  const s = screen(lang);
  const nameSafe = name;
  if (place === 1) return s.cheer1.replace("{name}", nameSafe);
  if (place === 2) return s.cheer2.replace("{name}", nameSafe);
  if (place === 3) return s.cheer3.replace("{name}", nameSafe);
  if (place > 3) return s.cheerN.replace("{place}", String(place)).replace("{name}", nameSafe);
  return s.cheer0.replace("{name}", nameSafe);
}

