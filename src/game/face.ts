export function placeWord(lang: Lang, n: number): string {
  const row = ORD[lang];
  if (n === 1) return row?.[0] ?? "1st";
  if (n === 2) return row?.[1] ?? "2nd";
  if (n === 3) return row?.[2] ?? "3rd";
  return lang === "en" || lang === "simple" ? `${n}th` : String(n);
}

