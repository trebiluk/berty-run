function core(lang: Lang): Ui {
  if (lang === "en" || lang === "simple" || lang === "es") return ACCESS_UI[lang] as unknown as Ui;
  const extra = EXTRA[lang] ?? {};
  const en = ACCESS_UI.en;
  return {
    ...en,
    ...extra,
    drives: { ...en.drives, ...(extra.drives as object) },
    cabs: { ...en.cabs, ...(extra.cabs as object) },
    skins: { ...en.skins, ...(extra.skins as object) },
    stickers: { ...en.stickers, ...(extra.stickers as object) },
  } as unknown as Ui;
}

export type Face = Ui & Screen & {
  playWord: string;
  levelsWord: string;
  nextWord: string;
  helpWord: string;
  whatsNew: string;
  closeWord: string;
  noVoice: string;
};

export function screen(lang: Lang): Screen {
  return SCREENS[lang] ?? EN;
}

export function face(lang: Lang): Face {
  const ui = { ...core(lang), ...screen(lang) } as Face;
  const put = (key: keyof Ui, sharedKey: string) => {
    const v = shared(sharedKey);
    if (v) (ui as unknown as Record<string, string>)[key as string] = v;
  };
  put("settings", "settings");
  put("language", "language");
  put("sound", "sound");
  put("home", "home");
  put("back", "back");
  put("signIn", "signIn");
  put("scores", "scores");
  put("pause", "pause");
  put("resume", "resume");
  put("retry", "retry");
  put("exit", "exit");
  put("music", "music");
  put("volume", "volume");
  const read = shared("readAloud");
  const bag = ui as unknown as Record<string, string>;
  if (read) bag.read = read;
  ui.playWord = shared("play") || "Play";
  ui.levelsWord = shared("levels") || "Levels";
  ui.nextWord = shared("next") || "Next";
  ui.helpWord = shared("help") || "Help";
  ui.whatsNew = shared("whatsNew") || "What's new";
  ui.closeWord = shared("close") || "Close";
  ui.noVoice = shared("noVoice") || "No voice yet. Read the words.";
  const menu = shared("menu");
  if (menu && (lang === "en" || lang === "simple" || menu !== "Menu")) bag.menu = menu;
  return ui;
}

